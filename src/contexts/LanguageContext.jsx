const LanguageContext = createContext(null);

export function LanguageProvider({ children }) {
  const [language, setLanguage] = useState(
    () => (window.localStorage.getItem("portfolio-language") === "ko" ? "ko" : "en"),
  );

  useEffect(() => {
    window.localStorage.setItem("portfolio-language", language);
    document.documentElement.lang = language;
    document.title = messages[language]["document.title"];
  }, [language]);

  const value = useMemo(
    () => ({
      language,
      toggleLanguage: () => setLanguage((current) => (current === "en" ? "ko" : "en")),
      t: (key) => messages[language][key] ?? messages.en[key] ?? key,
    }),
    [language],
  );

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context) throw new Error("useLanguage는 LanguageProvider 안에서만 사용할 수 있습니다");
  return context;
}
